package dev.arcdrift.core.rules

import dev.arcdrift.core.model.BoundaryRule
import dev.arcdrift.core.model.RulePolicy

/**
 * Generates runnable JUnit 5 + ArchUnit test classes in Kotlin from declarative [BoundaryRule]s
 * so architectural boundaries drawn on the ArcDrift canvas are enforced in CI/CD.
 */
object ArchUnitTestGenerator {

    private val KOTLIN_HARD_KEYWORDS = setOf(
        "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if",
        "in", "interface", "is", "null", "object", "package", "return", "super", "this",
        "throw", "true", "try", "typealias", "typeof", "val", "var", "when", "while"
    )

    fun generateKotlinJUnit5(
        projectName: String,
        basePackage: String,
        rules: List<BoundaryRule>,
        className: String = "ArcDriftArchitectureTest"
    ): String {
        val effectivePkg = sanitizePackageDeclaration(basePackage)
        val analyzePkg = basePackage.trim().ifEmpty { ".." }
        val safeClassName = sanitizeClassIdentifier(className)
        val safeKdocProject = sanitizeKdocText(projectName)

        val sb = StringBuilder()
        if (effectivePkg.isNotEmpty()) {
            sb.appendLine("package $effectivePkg")
            sb.appendLine()
        }
        sb.appendLine("import com.tngtech.archunit.base.DescribedPredicate")
        sb.appendLine("import com.tngtech.archunit.core.domain.JavaClass")
        sb.appendLine("import com.tngtech.archunit.core.importer.ImportOption")
        sb.appendLine("import com.tngtech.archunit.junit.AnalyzeClasses")
        sb.appendLine("import com.tngtech.archunit.junit.ArchTest")
        sb.appendLine("import com.tngtech.archunit.lang.ArchRule")
        sb.appendLine("import com.tngtech.archunit.lang.syntax.ArchRuleDefinition.classes")
        sb.appendLine("import com.tngtech.archunit.lang.syntax.ArchRuleDefinition.noClasses")
        sb.appendLine("import com.tngtech.archunit.library.dependencies.SlicesRuleDefinition.slices")
        sb.appendLine()
        sb.appendLine("/**")
        sb.appendLine(" * Auto-generated by ArcDrift (`arc check --generate-archunit`) for project '$safeKdocProject'.")
        sb.appendLine(" * Enforces `.arc.mmd` architectural guardrails in CI.")
        sb.appendLine(" */")
        sb.appendLine("@AnalyzeClasses(packages = [\"${escapeKotlinString(analyzePkg)}\"], importOptions = [ImportOption.DoNotIncludeTests::class])")
        sb.appendLine("class $safeClassName {")
        sb.appendLine()
        val slicePattern = if (basePackage.isBlank()) "(**)" else "${escapeKotlinString(basePackage.trim())}.(**)..*"
        sb.appendLine("    @ArchTest")
        sb.appendLine("    val freeOfPackageCycles: ArchRule = slices()")
        sb.appendLine("        .matching(\"$slicePattern\")")
        sb.appendLine("        .should().beFreeOfCycles()")

        val usedFieldNames = mutableSetOf("freeOfPackageCycles")
        for (rule in rules.sortedBy { it.id }) {
            val baseFieldName = toCamelIdentifier(rule.id)
            var fieldName = baseFieldName
            var suffix = 2
            while (!usedFieldNames.add(fieldName)) {
                fieldName = "${baseFieldName}_$suffix"
                suffix++
            }
            val fromChain = buildTargetClauseChain(rule.fromPattern, includeLeadingThat = true)
            val toChain = buildTargetClauseChain(rule.toPattern, includeLeadingThat = false)
            val becauseText = escapeKotlinString(rule.rationale.ifBlank { rule.name })

            sb.appendLine()
            sb.appendLine("    @ArchTest")
            when (rule.policy) {
                RulePolicy.FORBIDDEN -> {
                    val toDepClause = if (rule.toPattern.trim().startsWith("@")) {
                        val predExpr = buildAnnotationPredicateExpr(rule.toPattern.trim().removePrefix("@").trim())
                        ".should().dependOnClassesThat($predExpr)"
                    } else {
                        ".should().dependOnClassesThat()$toChain"
                    }
                    sb.appendLine("    val $fieldName: ArchRule = noClasses()")
                    sb.appendLine("        $fromChain")
                    sb.appendLine("        $toDepClause")
                    sb.appendLine("        .because(\"$becauseText\")")
                }
                RulePolicy.ALLOWED_ONLY -> {
                    val fromIsAnnotation = rule.fromPattern.trim().startsWith("@")
                    val toIsAnnotation = rule.toPattern.trim().startsWith("@")
                    val toClassMatch = extractClassNameConstraint(rule.toPattern)
                    sb.appendLine("    val $fieldName: ArchRule = classes()")
                    sb.appendLine("        $fromChain")
                    sb.appendLine("        .should().onlyDependOnClassesThat(")
                    if (!fromIsAnnotation && !toIsAnnotation && toClassMatch == null) {
                        val fromPkg = toArchUnitPackageMatcher(rule.fromPattern)
                        val toPkg = toArchUnitPackageMatcher(rule.toPattern)
                        sb.appendLine("            JavaClass.Predicates.resideInAnyPackage(\"${escapeKotlinString(fromPkg)}\", \"${escapeKotlinString(toPkg)}\", \"java..\", \"kotlin..\", \"org.jetbrains..\")")
                    } else {
                        val allowedExpr = buildJavaClassPredicateExpr(rule.toPattern, rule.fromPattern)
                        sb.appendLine("            $allowedExpr")
                    }
                    sb.appendLine("        )")
                    sb.appendLine("        .because(\"$becauseText\")")
                }
                RulePolicy.MUST_DEPEND_VIA_INTERFACE -> {
                    sb.appendLine("    val $fieldName: ArchRule = noClasses()")
                    sb.appendLine("        $fromChain")
                    if (rule.toPattern.trim().startsWith("@")) {
                        val predExpr = buildAnnotationPredicateExpr(rule.toPattern.trim().removePrefix("@").trim())
                        sb.appendLine("        .should().dependOnClassesThat($predExpr.and(DescribedPredicate.not(JavaClass.Predicates.INTERFACES)))")
                    } else {
                        sb.appendLine("        .should().dependOnClassesThat()")
                        sb.appendLine("        $toChain.and().areNotInterfaces()")
                    }
                    sb.appendLine("        .because(\"$becauseText\")")
                }
            }
        }

        sb.appendLine("}")
        return sb.toString()
    }

    private sealed interface ClassNameConstraint {
        data class Exact(val simpleName: String) : ClassNameConstraint
        data class Suffix(val suffix: String) : ClassNameConstraint
    }

    private fun buildTargetClauseChain(pattern: String, includeLeadingThat: Boolean): String {
        val prefix = if (includeLeadingThat) ".that()" else ""
        val trimmed = pattern.trim()
        if (trimmed.startsWith("@")) {
            val annName = trimmed.removePrefix("@").trim()
            val predExpr = buildAnnotationPredicateExpr(annName)
            return if (includeLeadingThat) ".that($predExpr)" else "($predExpr)"
        }
        val pkgMatcher = toArchUnitPackageMatcher(trimmed)
        val clsConstraint = extractClassNameConstraint(trimmed)
        return buildString {
            append("$prefix.resideInAnyPackage(\"${escapeKotlinString(pkgMatcher)}\")")
            when (clsConstraint) {
                is ClassNameConstraint.Exact -> append(".and().haveSimpleName(\"${escapeKotlinString(clsConstraint.simpleName)}\")")
                is ClassNameConstraint.Suffix -> append(".and().haveSimpleNameEndingWith(\"${escapeKotlinString(clsConstraint.suffix)}\")")
                null -> Unit
            }
        }
    }

    private fun buildAnnotationPredicateExpr(annPattern: String): String {
        val clean = annPattern.removePrefix("*")
        val isSuffix = annPattern.startsWith("*") && clean.isNotEmpty()
        val escapedAnn = escapeKotlinString(annPattern)
        val escapedClean = escapeKotlinString(clean)
        return if (annPattern.contains('.')) {
            "DescribedPredicate.describe(\"annotated with @$escapedAnn\") { cls: JavaClass -> cls.annotations.any { it.rawType.name == \"$escapedAnn\" } }"
        } else if (isSuffix) {
            "DescribedPredicate.describe(\"annotated with *@$escapedClean\") { cls: JavaClass -> cls.annotations.any { it.rawType.simpleName.endsWith(\"$escapedClean\") } }"
        } else {
            "DescribedPredicate.describe(\"annotated with @$escapedAnn\") { cls: JavaClass -> cls.annotations.any { it.rawType.simpleName == \"$escapedAnn\" } }"
        }
    }

    private fun buildJavaClassPredicateExpr(toPattern: String, fromPattern: String): String {
        val trimmedFrom = fromPattern.trim()
        val trimmedTo = toPattern.trim()
        val stdAndSelfAllowed = if (trimmedFrom.startsWith("@")) {
            val fromAnnPred = buildAnnotationPredicateExpr(trimmedFrom.removePrefix("@").trim())
            "JavaClass.Predicates.resideInAnyPackage(\"java..\", \"kotlin..\", \"org.jetbrains..\").or($fromAnnPred)"
        } else {
            val fromPkg = toArchUnitPackageMatcher(trimmedFrom)
            "JavaClass.Predicates.resideInAnyPackage(\"${escapeKotlinString(fromPkg)}\", \"java..\", \"kotlin..\", \"org.jetbrains..\")"
        }
        if (trimmedTo.startsWith("@")) {
            val annPred = buildAnnotationPredicateExpr(trimmedTo.removePrefix("@").trim())
            return "$stdAndSelfAllowed.or($annPred)"
        }
        val toPkg = toArchUnitPackageMatcher(trimmedTo)
        val pkgPred = "JavaClass.Predicates.resideInAnyPackage(\"${escapeKotlinString(toPkg)}\")"
        val clsConstraint = extractClassNameConstraint(trimmedTo)
        val targetPred = when (clsConstraint) {
            is ClassNameConstraint.Exact -> "$pkgPred.and(JavaClass.Predicates.simpleName(\"${escapeKotlinString(clsConstraint.simpleName)}\"))"
            is ClassNameConstraint.Suffix -> "$pkgPred.and(JavaClass.Predicates.simpleNameEndingWith(\"${escapeKotlinString(clsConstraint.suffix)}\"))"
            null -> pkgPred
        }
        return "$stdAndSelfAllowed.or($targetPred)"
    }

    private fun sanitizeKdocText(raw: String): String =
        raw.replace("/*", "/ *")
            .replace("*/", "* /")
            .replace("\r", "")
            .replace("\n", " ")

    private fun sanitizePackageDeclaration(rawPkg: String): String {
        val trimmed = rawPkg.trim()
        if (trimmed.isEmpty()) return ""
        return trimmed.split('.')
            .filter { it.isNotEmpty() }
            .joinToString(".") { seg ->
                val cleaned = seg.replace(Regex("[^a-zA-Z0-9_]"), "_")
                val nonDigit = if (cleaned.isNotEmpty() && cleaned[0].isDigit()) "_$cleaned" else cleaned.ifEmpty { "pkg" }
                if (nonDigit in KOTLIN_HARD_KEYWORDS) "`$nonDigit`" else nonDigit
            }
    }

    private fun sanitizeClassIdentifier(rawName: String): String {
        val cleaned = rawName.trim().replace(Regex("[^a-zA-Z0-9_]"), "_").ifEmpty { "ArcDriftArchitectureTest" }
        val nonDigit = if (cleaned[0].isDigit()) "_$cleaned" else cleaned
        return if (nonDigit in KOTLIN_HARD_KEYWORDS) "${nonDigit.replaceFirstChar { it.uppercaseChar() }}Test" else nonDigit
    }

    private fun escapeKotlinString(raw: String): String =
        raw
            .replace("\\", "\\\\")
            .replace("\"", "\\\"")
            .replace("$", "\\$")
            .replace("\n", "\\n")
            .replace("\r", "")

    private fun toCamelIdentifier(rawId: String): String {
        val parts = rawId.split(Regex("[^a-zA-Z0-9]+")).filter { it.isNotEmpty() }
        if (parts.isEmpty()) return "archRule"
        val first = parts.first().lowercase()
        val rest = parts.drop(1).joinToString("") { part ->
            part.lowercase().replaceFirstChar { it.uppercaseChar() }
        }
        val candidate = first + rest
        return when {
            candidate.first().isDigit() -> "rule_$candidate"
            candidate in KOTLIN_HARD_KEYWORDS -> "${candidate}Rule"
            else -> candidate
        }
    }

    private fun extractClassNameConstraint(pattern: String): ClassNameConstraint? {
        val trimmed = pattern.trim()
        if (trimmed.startsWith("@")) return null
        val lastSeg = trimmed.substringAfterLast('.')
        if (lastSeg.startsWith("*") && lastSeg.length > 1 && lastSeg[1].isUpperCase()) {
            val suffix = lastSeg.removePrefix("*").takeIf { it.all { ch -> ch.isLetterOrDigit() || ch == '_' } }
            if (suffix != null) return ClassNameConstraint.Suffix(suffix)
        }
        if (lastSeg.isNotEmpty() && lastSeg[0].isUpperCase() && lastSeg.all { it.isLetterOrDigit() || it == '_' }) {
            return ClassNameConstraint.Exact(lastSeg)
        }
        return null
    }

    private fun toArchUnitPackageMatcher(pattern: String): String {
        var trimmed = pattern.trim().removePrefix("@")
        val clsConstraint = extractClassNameConstraint(pattern)
        if (clsConstraint != null && trimmed.contains('.')) {
            trimmed = trimmed.substringBeforeLast('.') + ".*"
        } else if (clsConstraint != null) {
            return ".."
        }
        if (trimmed in setOf("*", "**", "..", "*.", ".*")) return ".."
        return trimmed
            .replace("*.", "..")
            .replace(".*", "..")
            .replace("*", "..")
            .replace(Regex("\\.{3,}"), "..")
            .let { if (!it.endsWith("..")) "$it.." else it }
    }
}
